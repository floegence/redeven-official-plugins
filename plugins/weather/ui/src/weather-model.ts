export function majorCitiesForLocale(
  locale: SupportedLocale,
): MajorCityLocation[] {
  const countries = new Intl.DisplayNames(locale, { type: "region" });
  return majorCityDefinitions.map(({ en, zh, ...location }, index) => ({
    ...location,
    ...(locale === "zh-CN"
      ? zh
      : locale === "en-US"
        ? en
        : {
            name: cityNames[locale]![index],
            admin1: "",
            country: countries.of(countryCodes[index]) ?? en.country,
          }),
  }));
}
export function localizedLocation(
  location: MajorCityLocation,
  locale: SupportedLocale,
): MajorCityLocation {
  return (
    majorCitiesForLocale(locale).find((city) => city.id === location.id) ??
    location
  );
}

export function conditionForCode(
  code: number,
  isDay: boolean,
): WeatherCondition {
  if (code === 0)
    return isDay
      ? { kind: "clear-day", symbol: "☀️", label: "Clear sky" }
      : { kind: "clear-night", symbol: "🌙", label: "Clear sky" };
  if (code === 1 || code === 2)
    return {
      kind: "partly-cloudy",
      symbol: isDay ? "🌤️" : "☁️",
      label: "Partly cloudy",
    };
  if (code === 3) return { kind: "cloudy", symbol: "☁️", label: "Cloudy" };
  if (code === 45 || code === 48)
    return { kind: "fog", symbol: "🌫️", label: "Fog" };
  if (code >= 51 && code <= 57)
    return { kind: "drizzle", symbol: "🌦️", label: "Drizzle" };
  if ((code >= 61 && code <= 67) || (code >= 80 && code <= 82))
    return { kind: "rain", symbol: "🌧️", label: "Rain" };
  if ((code >= 71 && code <= 77) || (code >= 85 && code <= 86))
    return { kind: "snow", symbol: "🌨️", label: "Snow" };
  if (code >= 95 && code <= 99)
    return { kind: "storm", symbol: "⛈️", label: "Thunderstorm" };
  return { kind: "unknown", symbol: "•", label: "Conditions unavailable" };
}

export function temperatureRangeClasses(
  days: readonly TemperatureDay[],
  day: TemperatureDay,
  currentTemperature?: number,
): TemperatureRangeClasses {
  const globalMinimum = Math.min(...days.map((value) => value.temperature_min));
  const globalMaximum = Math.max(...days.map((value) => value.temperature_max));
  const span = Math.max(1, globalMaximum - globalMinimum);
  const start = boundedStep((day.temperature_min - globalMinimum) / span);
  const end = boundedStep((day.temperature_max - globalMinimum) / span);
  const width = Math.max(1, end - start);
  const current =
    currentTemperature === undefined
      ? undefined
      : boundedStep((currentTemperature - globalMinimum) / span);
  return {
    startClass: `range-start-${start}`,
    widthClass: `range-width-${width}`,
    currentClass:
      current === undefined ? undefined : `current-position-${current}`,
  };
}

function boundedStep(value: number): number {
  return Math.max(0, Math.min(10, Math.round(value * 10)));
}
