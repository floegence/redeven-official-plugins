export type WeatherTranslations = {
  [K in keyof (typeof translations)["en-US"]]: K extends "conditions"
    ? Record<WeatherConditionKind, string>
    : string;
};
export type WeatherMessageKey = Exclude<
  keyof WeatherTranslations,
  "conditions"
>;
export function localeForLanguageTag(
  languageTag: string | undefined,
): SupportedLocale {
  const parts = (languageTag ?? "en")
    .toLowerCase()
    .replaceAll("_", "-")
    .split("-");
  if (parts[0] === "zh") {
    if (parts.includes("hans")) return "zh-CN";
    return parts.some((part) => ["hant", "tw", "hk", "mo"].includes(part))
      ? "zh-TW"
      : "zh-CN";
  }
  return (
    supportedLocales.find(
      (locale) => locale.toLowerCase().split("-")[0] === parts[0],
    ) ?? "en-US"
  );
}
export function translationsForLocale(
  locale: SupportedLocale,
): WeatherTranslations {
  return translations[locale];
}
export function formatMessage(
  locale: SupportedLocale,
  key: WeatherMessageKey,
  values: Record<string, string | number> = {},
): string {
  let text: string = translations[locale][key];
  for (const [name, value] of Object.entries(values))
    text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
export function formatCivilDate(
  value: string,
  locale: SupportedLocale,
  weekdayOnly = false,
): string {
  const date = new Date(`${value}T12:00:00Z`);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(locale, {
    timeZone: "UTC",
    ...(weekdayOnly
      ? { weekday: "short" as const }
      : {
          year: "numeric" as const,
          month: "long" as const,
          day: "numeric" as const,
        }),
  }).format(date);
}
